        private static double KernelTan(double x, double y, int iy)
        {
            /* one, pio4 and pio4lo live at TanXxx[13..15] in the C source */
            const double one = 1.00000000000000000000e+00;
            const double pio4 = 7.85398163397448278999e-01;
            const double pio4lo = 3.06161699786838301793e-17;

            unchecked
            {
                double z, r, v, w, s;
                int ix, hx;

                double[] T = TanXxx;

                ulong bx = ToBits(x);
                hx = unchecked((int)(uint)(bx >> 32)); /* high word of x */
                ix = hx & 0x7fffffff; /* high word of |x| */
                if (ix < 0x3e300000)
                { /* x < 2**-28 */
                    if ((int)x == 0)
                    { /* generate inexact */
                        if (((ix | unchecked((int)(uint)bx)) | (iy + 1)) == 0)
                            return one / Abs(x);
                        else
                        {
                            if (iy == 1)
                                return x;
                            else
                            { /* compute -1 / (x+y) carefully */
                                double a, t;

                                z = w = x + y;
                                z = ZeroLo(z);
                                v = y - (z - x);
                                t = a = -one / w;
                                t = ZeroLo(t);
                                s = Fma(t, z, one);
                                return Fma(a, Fma(t, v, s), t);
                            }
                        }
                    }
                }
                if (ix >= 0x3FE59428)
                { /* |x| >= 0.6744 */
                    if (hx < 0)
                    {
                        x = -x;
                        y = -y;
                    }
                    z = pio4 - x;
                    w = pio4lo - y;
                    x = z + w;
                    y = 0.0;
                }
                z = x * x;
                w = z * z;
                /*
                 * Break x^5*(T[1]+x^2*T[2]+...) into
                 * x^5(T[1]+x^4*T[3]+...+x^20*T[11]) +
                 * x^5(x^2*(T[2]+x^4*T[4]+...+x^22*[T12]))
                 */
                r = Fma(w, Fma(w, Fma(w, Fma(w, Fma(w, T[11], T[9]), T[7]), T[5]), T[3]), T[1]);
                v = z * Fma(w, Fma(w, Fma(w, Fma(w, Fma(w, T[12], T[10]), T[8]), T[6]), T[4]), T[2]);
                s = z * x;
                r = Fma(z, Fma(s, r + v, y), y);
                r = Fma(T[0], s, r);
                w = x + r;
                if (ix >= 0x3FE59428)
                {
                    v = (double)iy;
                    return (double)(1 - ((hx >> 30) & 2)) *
                           Fma(-2.0, x - (w * w / (w + v) - r), v);
                }
                if (iy == 1)
                    return w;
                else
                {
                    /*
                     * if allow error up to 2 ulp, simply return
                     * -1.0 / (x+r) here
                     */
                    /* compute -1.0 / (x+r) accurately */
                    double a, t;
                    z = w;
                    z = ZeroLo(z);
                    v = r - (z - x); /* z+v = r+x */
                    t = a = -1.0 / w; /* a = -1.0/w */
                    t = ZeroLo(t);
                    s = Fma(t, z, 1.0);
                    return Fma(a, Fma(t, v, s), t);
                }
            }
        }

