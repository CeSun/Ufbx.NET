        private static ulong ToBits(double x)
        {
            return unchecked((ulong)BitConverter.DoubleToInt64Bits(x));
        }

        private static double FromBits(ulong bits)
        {
            return BitConverter.Int64BitsToDouble(unchecked((long)bits));
        }

        // ufbxm_hi: high 32-bit word of the double, as int
        private static int Hi(double x)
        {
            return unchecked((int)(uint)(ToBits(x) >> 32));
        }

        // low 32-bit word of the double, as uint
        private static uint Lo(double x)
        {
            return unchecked((uint)ToBits(x));
        }

        // ufbxm_from_bits
        private static double FromHiLo(int hi, uint lo)
        {
            return FromBits(((ulong)(uint)hi << 32) | lo);
        }

        // ufbxm_zero_lo
        private static double ZeroLo(double x)
        {
            return FromHiLo(Hi(x), 0u);
        }

        // ufbxm_set_hi
        private static double SetHi(double x, int hi)
        {
            return FromHiLo(hi, Lo(x));
        }

        // ------------------------------------------------------------------
        // ufbx_copysign, ufbx_math.c:150-155
        // ------------------------------------------------------------------

        public static double CopySign(double x, double y)
        {
            unchecked
            {
                int xh = Hi(x);
                int yh = Hi(y);
                return FromHiLo((xh & 0x7fffffff) | (yh & unchecked((int)0x80000000u)), Lo(x));
            }
        }

        // ------------------------------------------------------------------
        // ufbx_fabs, ufbx_math.c:157-165 (SSE path: andnot with -0.0)
        // ------------------------------------------------------------------

        public static double Abs(double x)
        {
            return FromBits(ToBits(x) & 0x7fffffffffffffffUL);
        }

