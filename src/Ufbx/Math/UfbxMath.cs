        internal static double Scalbn(double x, int n)
        {
            const double two54 = 1.80143985094819840000e+16;  /* 0x43500000, 0x00000000 */
            const double twom54 = 5.55111512312578270212e-17; /* 0x3C900000, 0x00000000 */
            const double huge = 1.0e+300;
            const double tiny = 1.0e-300;

            unchecked
            {
                int k, hx;
                uint lx;
                ulong bx = ToBits(x);
                hx = unchecked((int)(uint)(bx >> 32));
                lx = (uint)bx;
                k = (hx & 0x7ff00000) >> 20; /* extract exponent */
                if (k == 0)
                { /* 0 or subnormal x */
                    if ((lx | (uint)(hx & 0x7fffffff)) == 0)
                        return x; /* +-0 */
                    x *= two54;
                    bx = ToBits(x);
                    hx = unchecked((int)(uint)(bx >> 32));
                    k = ((hx & 0x7ff00000) >> 20) - 54;
                    if (n < -50000)
                        return tiny * x; /* underflow */
                }
                if (k == 0x7ff)
                    return x + x; /* NaN or Inf */
                k = k + n;
                if (k > 0x7fe)
                    return huge * CopySign(huge, x); /* overflow */
                if (k > 0) /* normal result */
                {
                    hx = (hx & unchecked((int)0x800fffffu)) | (k << 20);
                    return FromHiLo(hx, (uint)bx);
                }
                if (k <= -54)
                {
                    if (n > 50000) /* in case integer overflow in n+k */
                        return huge * CopySign(huge, x); /* overflow */
                    else
                        return tiny * CopySign(tiny, x); /* underflow */
                }
                k += 54; /* subnormal result */
                hx = (hx & unchecked((int)0x800fffffu)) | (k << 20);
                return FromHiLo(hx, (uint)bx) * twom54;
            }
        }

