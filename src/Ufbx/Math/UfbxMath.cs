        private static int KernelRemPio2(double[] x, double[] y, int e0, int nx, int prec, int[] ipio2)
        {
            const double zero = 0.0;
            const double one = 1.0;
            const double two24 = 1.67772160000000000000e+07;  /* 0x41700000, 0x00000000 */
            const double twon24 = 5.96046447753906250000e-08; /* 0x3E700000, 0x00000000 */

            unchecked
            {
                int jz, jx, jv, jp, jk, carry, n, i, j, k, m, q0, ih;
                int[] iq = new int[20];
                double z, fw;
                double[] f = new double[20];
                double[] fq = new double[20];
                double[] q = new double[20];

                /* initialize jk */
                jk = KernelRemPio2InitJk[prec];
                jp = jk;

                /* determine jx,jv,q0, note that 3>q0 */
                jx = nx - 1;
                jv = (e0 - 3) / 24;
                if (jv < 0)
                    jv = 0;
                q0 = e0 - 24 * (jv + 1);

                /* set up f[0] to f[jx+jk] where f[jx+jk] = ipio2[jv+jk] */
                j = jv - jx;
                m = jx + jk;
                for (i = 0; i <= m; i++, j++)
                    f[i] = (j < 0) ? zero : (double)ipio2[j];

                /* compute q[0],q[1],...q[jk] */
                for (i = 0; i <= jk; i++)
                {
                    fw = 0.0;
                    for (j = 0; j <= jx; j++)
                        fw = Fma(x[j], f[jx + i - j], fw);
                    q[i] = fw;
                }

                jz = jk;

                for (;;)
                {
                    /* distill q[] into iq[] reversingly */
                    i = 0;
                    j = jz;
                    z = q[jz];
                    for (; j > 0; i++, j--)
                    {
                        fw = (double)(int)(twon24 * z);
                        iq[i] = (int)(z - two24 * fw);
                        z = q[j - 1] + fw;
                    }

                    /* compute n */
                    z = Scalbn(z, q0); /* actual value of z */
                    z -= 8.0 * Floor(z * 0.125); /* trim off integer >= 8 */
                    n = (int)z;
                    z -= (double)n;
                    ih = 0;
                    if (q0 > 0)
                    { /* need iq[jz-1] to determine n */
                        i = iq[jz - 1] >> (24 - q0);
                        n += i;
                        iq[jz - 1] -= i << (24 - q0);
                        ih = iq[jz - 1] >> (23 - q0);
                    }
                    else if (q0 == 0)
                    {
                        ih = iq[jz - 1] >> 23;
                    }
                    else if (z >= 0.5)
                    {
                        ih = 2;
                    }

                    if (ih > 0)
                    { /* q > 0.5 */
                        n += 1;
                        carry = 0;
                        for (i = 0; i < jz; i++)
                        { /* compute 1-q */
                            j = iq[i];
                            if (carry == 0)
                            {
                                if (j != 0)
                                {
                                    carry = 1;
                                    iq[i] = 0x1000000 - j;
                                }
                            }
                            else
                                iq[i] = 0xffffff - j;
                        }
                        if (q0 > 0)
                        { /* rare case: chance is 1 in 12 */
                            switch (q0)
                            {
                                case 1:
                                    iq[jz - 1] &= 0x7fffff;
                                    break;
                                case 2:
                                    iq[jz - 1] &= 0x3fffff;
                                    break;
                                default: break;
                            }
                        }
                        if (ih == 2)
                        {
                            z = one - z;
                            if (carry != 0)
                                z -= Scalbn(one, q0);
                        }
                    }

                    /* check if recomputation is needed */
                    if (z == zero)
                    {
                        j = 0;
                        for (i = jz - 1; i >= jk; i--)
                            j |= iq[i];
                        if (j == 0)
                        { /* need recomputation */
                            for (k = 1; iq[jk - k] == 0; k++)
                                ; /* k = no. of terms needed */

                            for (i = jz + 1; i <= jz + k; i++)
                            { /* add q[jz+1] to q[jz+k] */
                                f[jx + i] = (double)ipio2[jv + i];
                                fw = 0.0;
                                for (j = 0; j <= jx; j++)
                                    fw = Fma(x[j], f[jx + i - j], fw);
                                q[i] = fw;
                            }
                            jz += k;
                            // goto recompute;
                            continue;
                        }
                    }

                    break;
                }

                /* chop off zero terms */
                if (z == 0.0)
                {
                    jz -= 1;
                    q0 -= 24;
                    while (iq[jz] == 0)
                    {
                        jz--;
                        q0 -= 24;
                    }
                }
                else
                { /* break z into 24-bit if necessary */
                    z = Scalbn(z, -q0);
                    if (z >= two24)
                    {
                        fw = (double)(int)(twon24 * z);
                        iq[jz] = (int)(z - two24 * fw);
                        jz += 1;
                        q0 += 24;
                        iq[jz] = (int)fw;
                    }
                    else
                        iq[jz] = (int)z;
                }

                /* convert integer "bit" chunk to floating-point value */
                fw = Scalbn(one, q0);
                for (i = jz; i >= 0; i--)
                {
                    q[i] = fw * (double)iq[i];
                    fw *= twon24;
                }

                /* compute PIo2[0,...,jp]*q[jz,...,0] */
                fq[0] = 0.0; /* dumb warning fix */
                for (i = jz; i >= 0; i--)
                {
                    fw = 0.0;
                    for (k = 0; k <= jp && k <= jz - i; k++)
                        fw = Fma(KernelRemPio2PIo2[k], q[i + k], fw);
                    fq[jz - i] = fw;
                }

                /* compress fq[] into y[] */
                switch (prec)
                {
                    case 0:
                        {
                            fw = 0.0;
                            for (i = jz; i >= 0; i--)
                                fw += fq[i];
                            y[0] = (ih == 0) ? fw : -fw;
                            break;
                        }
                    case 1:
                    case 2:
                        {
                            fw = 0.0;
                            for (i = jz; i >= 0; i--)
                                fw += fq[i];
                            y[0] = (ih == 0) ? fw : -fw;
                            fw = fq[0] - fw;
                            for (i = 1; i <= jz; i++)
                                fw += fq[i];
                            y[1] = (ih == 0) ? fw : -fw;
                            break;
                        }
                    case 3: /* painful */
                        {
                            for (i = jz; i > 0; i--)
                            {
                                fw = fq[i - 1] + fq[i];
                                fq[i] += fq[i - 1] - fw;
                                fq[i - 1] = fw;
                            }
                            for (i = jz; i > 1; i--)
                            {
                                fw = fq[i - 1] + fq[i];
                                fq[i] += fq[i - 1] - fw;
                                fq[i - 1] = fw;
                            }
                            fw = 0.0;
                            for (i = jz; i >= 2; i--)
                                fw += fq[i];
                            if (ih == 0)
                            {
                                y[0] = fq[0];
                                y[1] = fq[1];
                                y[2] = fw;
                            }
                            else
                            {
                                y[0] = -fq[0];
                                y[1] = -fq[1];
                                y[2] = -fw;
                            }
                            break;
                        }
                    default: break;
                }
                return n & 7;
            }
        }

        private static int RemPio2(double x, double[] y)
        {
            const double half = 5.00000000000000000000e-01;    /* 0x3FE00000, 0x00000000 */
            const double two24 = 1.67772160000000000000e+07;   /* 0x41700000, 0x00000000 */
            const double invpio2 = 6.36619772367581382433e-01; /* 0x3FE45F30, 0x6DC9C883 */
            const double pio2_1 = 1.57079632673412561417e+00;  /* 0x3FF921FB, 0x54400000 */
            const double pio2_1t = 6.07710050650619224932e-11; /* 0x3DD0B461, 0x1A626331 */
            const double pio2_2 = 6.07710050630396597660e-11;  /* 0x3DD0B461, 0x1A600000 */
            const double pio2_2t = 2.02226624879595063154e-21; /* 0x3BA3198A, 0x2E037073 */
            const double pio2_3 = 2.02226624871116645580e-21;  /* 0x3BA3198A, 0x2E000000 */
            const double pio2_3t = 8.47842766036889956997e-32; /* 0x397B839A, 0x252049C1 */

            unchecked
            {
                double z, w, t, r, fn;
                double[] tx = new double[3];
                int e0, i, j, nx, n, ix, hx;

                ulong bx = ToBits(x);
                hx = unchecked((int)(uint)(bx >> 32)); /* high word of x */
                ix = hx & 0x7fffffff;
                if (ix <= 0x3fe921fb) /* |x| ~<= pi/4 , no need for reduction */
                {
                    y[0] = x;
                    y[1] = 0;
                    return 0;
                }
                if (ix < 0x4002d97c)
                { /* |x| < 3pi/4, special case with n=+-1 */
                    if (hx > 0)
                    {
                        z = x - pio2_1;
                        if (ix != 0x3ff921fb)
                        { /* 33+53 bit pi is good enough */
                            y[0] = z - pio2_1t;
                            y[1] = (z - y[0]) - pio2_1t;
                        }
                        else
                        { /* near pi/2, use 33+33+53 bit pi */
                            z -= pio2_2;
                            y[0] = z - pio2_2t;
                            y[1] = (z - y[0]) - pio2_2t;
                        }
                        return 1;
                    }
                    else
                    { /* negative x */
                        z = x + pio2_1;
                        if (ix != 0x3ff921fb)
                        { /* 33+53 bit pi is good enough */
                            y[0] = z + pio2_1t;
                            y[1] = (z - y[0]) + pio2_1t;
                        }
                        else
                        { /* near pi/2, use 33+33+53 bit pi */
                            z += pio2_2;
                            y[0] = z + pio2_2t;
                            y[1] = (z - y[0]) + pio2_2t;
                        }
                        return -1;
                    }
                }
                if (ix <= 0x413921fb)
                { /* |x| ~<= 2^19*(pi/2), medium size */
                    t = Abs(x);
                    n = (int)Fma(t, invpio2, half);
                    fn = (double)n;
                    r = Fma(-fn, pio2_1, t);
                    w = fn * pio2_1t; /* 1st round good to 85 bit */
                    if (n < 32 && ix != Npio2Hw[n - 1])
                    {
                        y[0] = r - w; /* quick check no cancellation */
                    }
                    else
                    {
                        j = ix >> 20;
                        y[0] = r - w;
                        i = j - ((Hi(y[0]) >> 20) & 0x7ff);
                        if (i > 16)
                        { /* 2nd iteration needed, good to 118 */
                            t = r;
                            w = fn * pio2_2;
                            r = t - w;
                            w = Fma(fn, pio2_2t, -((t - r) - w));
                            y[0] = r - w;
                            i = j - ((Hi(y[0]) >> 20) & 0x7ff);
                            if (i > 49)
                            { /* 3rd iteration need, 151 bits acc */
                                t = r; /* will cover all possible cases */
                                w = fn * pio2_3;
                                r = t - w;
                                w = Fma(fn, pio2_3t, -((t - r) - w));
                                y[0] = r - w;
                            }
                        }
                    }
                    y[1] = (r - y[0]) - w;
                    if (hx < 0)
                    {
                        y[0] = -y[0];
                        y[1] = -y[1];
                        return -n;
                    }
                    else
                        return n;
                }
                /*
                 * all other (large) arguments
                 */
                if (ix >= 0x7ff00000)
                { /* x is inf or NaN */
                    y[0] = x - x;
                    y[1] = x - x;
                    return 0;
                }
                /* set z = scalbn(|x|,ilogb(x)-23) */
                e0 = (ix >> 20) - 1046; /* e0 = ilogb(z)-23; */
                z = FromHiLo(ix - (e0 << 20), (uint)bx);
                for (i = 0; i < 2; i++)
                {
                    tx[i] = (double)(int)z;
                    z = (z - tx[i]) * two24;
                }
                tx[2] = z;
                nx = 3;
                while (tx[nx - 1] == 0.0)
                    nx--; /* skip zero term */
                n = KernelRemPio2(tx, y, e0, nx, 2, TwoOverPi);
                if (hx < 0)
                {
                    y[0] = -y[0];
                    y[1] = -y[1];
                    return -n;
                }
                return n;
            }
        }

