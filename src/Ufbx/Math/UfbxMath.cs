        public static double Ceil(double x)
        {
            const double huge = 1.0e300;

            unchecked
            {
                int i0, i1, j0;
                uint i, j;
                ulong bx = ToBits(x);
                i0 = unchecked((int)(uint)(bx >> 32));
                i1 = unchecked((int)(uint)bx);
                j0 = ((i0 >> 20) & 0x7ff) - 0x3ff;
                if (j0 < 20)
                {
                    if (j0 < 0)
                    { /* raise inexact if x != 0 */
                        if (huge + x > 0.0)
                        { /* return 0*sign(x) if |x|<1 */
                            if (i0 < 0)
                            {
                                i0 = unchecked((int)0x80000000u);
                                i1 = 0;
                            }
                            else if ((i0 | i1) != 0)
                            {
                                i0 = unchecked((int)0x3ff00000u);
                                i1 = 0;
                            }
                        }
                    }
                    else
                    {
                        i = 0x000fffffu >> j0;
                        if (((i0 & unchecked((int)i)) | i1) == 0)
                            return x; /* x is integral */
                        if (huge + x > 0.0)
                        { /* raise inexact flag */
                            if (i0 > 0)
                                i0 += 0x00100000 >> j0;
                            i0 &= unchecked((int)~i);
                            i1 = 0;
                        }
                    }
                }
                else if (j0 > 51)
                {
                    if (j0 == 0x400)
                        return x + x; /* inf or NaN */
                    else
                        return x; /* x is integral */
                }
                else
                {
                    i = 0xffffffffu >> (j0 - 20);
                    if ((i1 & unchecked((int)i)) == 0)
                        return x; /* x is integral */
                    if (huge + x > 0.0)
                    { /* raise inexact flag */
                        if (i0 > 0)
                        {
                            if (j0 == 20)
                                i0 += 1;
                            else
                            {
                                j = (uint)i1 + (1u << (52 - j0));
                                if (j < (uint)i1)
                                    i0 += 1; /* got a carry */
                                i1 = unchecked((int)j);
                            }
                        }
                        i1 &= unchecked((int)~i);
                    }
                }
                return FromHiLo(i0, (uint)i1);
            }
        }

