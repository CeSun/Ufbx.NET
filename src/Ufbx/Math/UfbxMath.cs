        public static double NextAfter(double x, double y)
        {
            unchecked
            {
                int hx, hy, ix, iy;
                uint lx, ly;
                ulong bx = ToBits(x);
                ulong by = ToBits(y);

                hx = unchecked((int)(uint)(bx >> 32)); /* high word of x */
                lx = (uint)bx; /* low  word of x */
                hy = unchecked((int)(uint)(by >> 32)); /* high word of y */
                ly = (uint)by; /* low  word of y */
                ix = hx & 0x7fffffff; /* |x| */
                iy = hy & 0x7fffffff; /* |y| */

                if (((ix >= 0x7ff00000) && ((ix - 0x7ff00000) | unchecked((int)lx)) != 0) || /* x is nan */
                    ((iy >= 0x7ff00000) && ((iy - 0x7ff00000) | unchecked((int)ly)) != 0)) /* y is nan */
                    return x + y;
                if (x == y)
                    return x; /* x=y, return x */
                if ((ix | unchecked((int)lx)) == 0)
                { /* x == 0 */
                    x = FromHiLo(hy & unchecked((int)0x80000000u), 1u);
                    y = x * x;
                    if (y == x)
                        return y;
                    else
                        return x; /* raise underflow flag */
                }
                if (hx >= 0)
                { /* x > 0 */
                    if (hx > hy || ((hx == hy) && (lx > ly)))
                    { /* x > y, x -= ulp */
                        if (lx == 0)
                            hx -= 1;
                        lx -= 1;
                    }
                    else
                    { /* x < y, x += ulp */
                        lx += 1;
                        if (lx == 0)
                            hx += 1;
                    }
                }
                else
                { /* x < 0 */
                    if (hy >= 0 || hx > hy || ((hx == hy) && (lx > ly)))
                    { /* x < y, x -= ulp */
                        if (lx == 0)
                            hx -= 1;
                        lx -= 1;
                    }
                    else
                    { /* x > y, x += ulp */
                        lx += 1;
                        if (lx == 0)
                            hx += 1;
                    }
                }
                hy = hx & 0x7ff00000;
                if (hy >= 0x7ff00000)
                    return x + x; /* overflow */
                if (hy < 0x00100000)
                { /* underflow */
                    y = x * x;
                    if (y != x)
                    { /* raise underflow flag */
                        return FromHiLo(hx, lx);
                    }
                }
                return FromHiLo(hx, lx);
            }
        }

