        private static int IsNanInt(double x)
        {
            unchecked
            {
                int hx;
                uint lx;
                ulong bx = ToBits(x);
                hx = unchecked((int)(uint)(bx >> 32)) & 0x7fffffff;
                lx = (uint)bx;
                hx |= unchecked((int)((lx | (0u - lx)) >> 31));
                hx = 0x7ff00000 - hx;
                return (int)((uint)hx >> 31);
            }
        }

        public static bool IsNan(double x)
        {
            return IsNanInt(x) != 0;
        }
