        // ufbx_frexp, ufbx_math.c:286-310 (kept for completeness; unused here)
        // ------------------------------------------------------------------

        internal static double Frexp(double x, out int e)
        {
            const double two54 = 1.80143985094819840000e+16; /* 0x43500000, 0x00000000 */

            unchecked
            {
                int hx, ix;
                uint lx;
                ulong bx = ToBits(x);
                hx = unchecked((int)(uint)(bx >> 32));
                lx = (uint)bx;
                ix = 0x7fffffff & hx;
                e = 0;
                if (ix >= 0x7ff00000 || ((ix | unchecked((int)lx)) == 0))
                    return x; /* 0,inf,nan */
                if (ix < 0x00100000)
                { /* subnormal */
                    x *= two54;
                    bx = ToBits(x);
                    hx = unchecked((int)(uint)(bx >> 32));
                    ix = hx & 0x7fffffff;
                    e = -54;
                }
                e += (ix >> 20) - 1022;
                hx = (hx & unchecked((int)0x800fffffu)) | 0x3fe00000;
                return FromHiLo(hx, (uint)bx);
            }
        }

