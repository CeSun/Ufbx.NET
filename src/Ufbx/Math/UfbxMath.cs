        public static double Atan(double x)
        {
            const double one = 1.0;
            const double huge = 1.0e300;

            unchecked
            {
                double w, s1, s2, z;
                int ix, hx, id;

                ulong bx = ToBits(x);
                hx = unchecked((int)(uint)(bx >> 32));
                ix = hx & 0x7fffffff;
                if (ix >= 0x44100000)
                { /* if |x| >= 2^66 */
                    if (ix > 0x7ff00000 ||
                        (ix == 0x7ff00000 && (uint)bx != 0))
                        return x + x; /* NaN */
                    if (hx > 0)
                        return AtanHi[3] + AtanLo[3];
                    else
                        return -AtanHi[3] - AtanLo[3];
                }
                if (ix < 0x3fdc0000)
                { /* |x| < 0.4375 */
                    if (ix < 0x3e200000)
                    { /* |x| < 2^-29 */
                        if (huge + x > one)
                            return x; /* raise inexact */
                    }
                    id = -1;
                }
                else
                {
                    x = Abs(x);
                    if (ix < 0x3ff30000)
                    { /* |x| < 1.1875 */
                        if (ix < 0x3fe60000)
                        { /* 7/16 <=|x|<11/16 */
                            id = 0;
                            x = Fma(2.0, x, -one) / (2.0 + x);
                        }
                        else
                        { /* 11/16<=|x|< 19/16 */
                            id = 1;
                            x = (x - one) / (x + one);
                        }
                    }
                    else
                    {
                        if (ix < 0x40038000)
                        { /* |x| < 2.4375 */
                            id = 2;
                            x = (x - 1.5) / Fma(1.5, x, one);
                        }
                        else
                        { /* 2.4375 <= |x| < 2^66 */
                            id = 3;
                            x = -1.0 / x;
                        }
                    }
                }
                /* end of argument reduction */
                z = x * x;
                w = z * z;
                /* break sum from i=0 to 10 aT[i]z**(i+1) into odd and even poly */
                s1 = z * Fma(w, Fma(w, Fma(w, Fma(w, Fma(w, AtanT[10], AtanT[8]), AtanT[6]), AtanT[4]), AtanT[2]), AtanT[0]);
                s2 = w * Fma(w, Fma(w, Fma(w, Fma(w, AtanT[9], AtanT[7]), AtanT[5]), AtanT[3]), AtanT[1]);
                if (id < 0)
                    return Fma(-x, s1 + s2, x);
                else
                {
                    z = AtanHi[id] - (Fma(x, s1 + s2, -AtanLo[id]) - x);
                    return (hx < 0) ? -z : z;
                }
            }
        }

