        // ufbx_rint, ufbx_math.c:2022-2074 (round-to-nearest-even; relies on
        // the default IEEE rounding mode, as the C implementation does)
        // ------------------------------------------------------------------

        private static readonly double[] Two52 =
        {
            4.50359962737049600000e+15,  /* 0x43300000, 0x00000000 */
            -4.50359962737049600000e+15, /* 0xC3300000, 0x00000000 */
        };

        public static double Rint(double x)
        {
            unchecked
            {
                int i0, j0, sx;
                uint i, i1;
                double w, t;
                ulong bt;
                ulong bx = ToBits(x);
                i0 = unchecked((int)(uint)(bx >> 32));
                i1 = (uint)bx;
                sx = (i0 >> 31) & 1;
                j0 = ((i0 >> 20) & 0x7ff) - 0x3ff;
                if (j0 < 20)
                {
                    if (j0 < 0)
                    {
                        if (((i0 & 0x7fffffff) | unchecked((int)i1)) == 0) return x;
                        i1 |= (uint)(i0 & 0x0fffff);
                        i0 &= unchecked((int)0xfffe0000u);
                        i0 |= unchecked((int)((i1 | (uint)(-(int)i1)) >> 12)) & 0x80000;
                        x = SetHi(x, i0);
                        w = Two52[sx] + x;
                        t = w - Two52[sx];
                        bt = ToBits(t);
                        i0 = unchecked((int)(uint)(bt >> 32));
                        t = FromHiLo((i0 & 0x7fffffff) | (sx << 31), (uint)bt);
                        return t;
                    }
                    else
                    {
                        i = 0x000fffffu >> j0;
                        if (((i0 & unchecked((int)i)) | unchecked((int)i1)) == 0) return x; /* x is integral */
                        i >>= 1;
                        if (((i0 & unchecked((int)i)) | unchecked((int)i1)) != 0)
                        {
                            if (j0 == 19) i1 = 0x40000000;
                            else i0 = (i0 & unchecked((int)~i)) | (0x20000 >> j0);
                        }
                    }
                }
                else if (j0 > 51)
                {
                    if (j0 == 0x400) return x + x; /* inf or NaN */
                    else return x; /* x is integral */
                }
                else
                {
                    i = 0xffffffffu >> (j0 - 20);
                    if ((i1 & i) == 0) return x; /* x is integral */
                    i >>= 1;
                    if ((i1 & i) != 0) i1 = (i1 & ~i) | (0x40000000u >> (j0 - 20));
                }
                x = FromHiLo(i0, i1);
                w = Two52[sx] + x;
                return w - Two52[sx];
            }
        }

